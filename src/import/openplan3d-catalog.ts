/**
 * A RoomPlan object `category` that is not a catalogue id, as OpenPlan3D's
 * `importedFurnitureCategory` maps it (`bed` is decided by width, below).
 */
export const ROOMPLAN_CATEGORY_ALIASES: Readonly<Record<string, string>> = {
  refrigerator: "fridge",
  sink: "sink_b",
  washerDryer: "washer_dryer",
  washerdryer: "washer_dryer",
};

/** `importedFurnitureCategory`: the catalogue id a RoomPlan object category becomes, or null. */
export function roomPlanCatalogId(category: string, widthCm: number): string | null {
  if (Object.hasOwn(OPENPLAN3D_CATALOG_SIZES, category)) return category;
  if (category === "bed") return widthCm > 140 ? "bed_queen" : "bed_twin";
  if (Object.hasOwn(ROOMPLAN_CATEGORY_ALIASES, category)) return ROOMPLAN_CATEGORY_ALIASES[category]!;
  return null;
}
