/**
 * Generate the raw-markdown section of `docs-site/public/_headers`: one explicit
 * `Content-Type: text/markdown; charset=utf-8` rule per published `.md` route.
 *
 * Why not one `/*.md` glob: a glob also matches a MISSING `/whatever.md`, so the
 * static-asset layer's 404 HTML page was labelled `text/markdown`. A rule per route can
 * only label a file that exists. The routes are the `dest` column of `PAGES` and
 * `SITE_PAGES` in `docs-site/sync-docs.mjs` (the single source of truth, parsed here
 * and never retyped); only the region between the BEGIN/END markers is rewritten.
 *
 * Each rule also sends `X-Robots-Tag: noindex` (GS-D7): the HTML page, not its raw markdown
 * twin, is the search result. The copy stays fetchable and the page's `rel=alternate` link stays;
 * `/llms.txt`, `/llms-full.txt`, the JSON schemas and every HTML route have no rule here, so they carry
 * no such header. The raw `.arch` and `.glb` files get the same header ({@link RAW_FILE_RULES}).
 *
 * One exact-path rule per page means the rule count grows with the site; Cloudflare documents
 * a cap on rules per `_headers` file (100 at the time of writing), so watch it.
 *
 * {@link renderHeaders} is pure so `test/docs-headers-drift.test.ts` can regenerate in
 * memory. Run `npm run gen:docs-headers` after editing the tables; CI asserts no drift.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const SYNC = "docs-site/sync-docs.mjs";
const HEADERS = "docs-site/public/_headers";

export const BEGIN =
  "# BEGIN GENERATED by `npm run gen:docs-headers` — do not edit; edit the tables in docs-site/sync-docs.mjs";
export const END = "# END GENERATED";

/** The `dest` column of one of sync-docs.mjs's literal `["src", "dest"],` tables. */
export function tableDests(syncSrc: string, name: string): string[] {
  const block = new RegExp(`const ${name} = \\[([\\s\\S]*?)\\n\\];`).exec(syncSrc);
  if (!block) throw new Error(`${SYNC} no longer declares \`const ${name} = [ … ];\``);
  const rows = [...block[1]!.matchAll(/\["([^"]+)",\s*"([^"]*)"\]/g)].map((m) => m[2]!);
  if (rows.length === 0) throw new Error(`\`${name}\` in ${SYNC} parsed to zero rows`);
  return rows;
}

/** Every `.md` route sync-docs publishes, in table order (PAGES then SITE_PAGES). */
export function markdownRoutes(syncSrc: string): string[] {
  return [...tableDests(syncSrc, "PAGES"), ...tableDests(syncSrc, "SITE_PAGES")];
}

/**
 * The raw plan and model files the docs host publishes (`sync-docs.mjs` writes `public/examples/*.arch`
 * and `public/gallery/*.arch`; `npm run gen:3d-assets` writes `public/3d/*.glb`), de-indexed like the `.md`
 * copies (GSC listed them "Crawled - currently not indexed", 2026-11-09). One single-splat rule per
 * directory and extension: Cloudflare's `_headers` allows ONE splat per path, which matches greedily
 * (`/examples/*.arch` is the rule smoke-tested since the gallery shipped). A `.arch` source is also
 * typed UTF-8 text, since the extension is unknown to the host and would download. The `.glb` is already
 * typed `model/gltf-binary` by the host, so it gets the robots header only.
 */
export const RAW_FILE_RULES: ReadonlyArray<{ path: string; contentType?: string }> = [
  { path: "/examples/*.arch", contentType: "text/plain; charset=utf-8" },
  { path: "/gallery/*.arch", contentType: "text/plain; charset=utf-8" },
  { path: "/3d/*.glb" },
];

/** The generated region, markers included. */
export function renderSection(routes: readonly string[]): string {
  const rules = [
    ...routes.map((r) => `/${r}\n  Content-Type: text/markdown; charset=utf-8\n  X-Robots-Tag: noindex`),
    ...RAW_FILE_RULES.map(
      (r) => `${r.path}\n${r.contentType ? `  Content-Type: ${r.contentType}\n` : ""}  X-Robots-Tag: noindex`,
    ),
  ].join("\n\n");
  return `${BEGIN}\n\n${rules}\n\n${END}`;
}

/** `current` with the region between the markers replaced by the section for `routes`. */
export function renderHeaders(current: string, routes: readonly string[]): string {
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start < 0 || end < start) {
    throw new Error(`${HEADERS} has lost its generated-section markers (\`${BEGIN}\` … \`${END}\`)`);
  }
  return current.slice(0, start) + renderSection(routes) + current.slice(end + END.length);
}

function main(): void {
  const routes = markdownRoutes(readFileSync(resolve(ROOT, SYNC), "utf8"));
  const path = resolve(ROOT, HEADERS);
  writeFileSync(path, renderHeaders(readFileSync(path, "utf8"), routes));
  process.stdout.write(`✓ generated ${routes.length} .md Content-Type rules in ${HEADERS}\n`);
}

// Run only when invoked directly (not when imported by the drift test).
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
