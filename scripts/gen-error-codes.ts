/**
 * Generate `docs/error-codes.md`, `src/error-catalog-fixes.ts` and `src/error-catalog-fixes-intent.ts`
 * from the error catalog (`src/error-catalog.ts`).
 *
 * Run `npm run gen:errors` after editing the catalog. A drift test
 * (`test/explain.test.ts`) regenerates and asserts the committed files match, so
 * the reference, the fix table and the catalog can never diverge.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { ERROR_CATALOG, ERROR_CODES } from "../src/error-catalog.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");

/** The full `docs/error-codes.md` content (string), generated from the catalog. */
export function renderErrorCodes(): string {
  const errors = ERROR_CODES.filter((c) => ERROR_CATALOG[c]!.severity === "error");
  const warnings = ERROR_CODES.filter((c) => ERROR_CATALOG[c]!.severity === "warning");

  const out: string[] = [
    "<!-- GENERATED by scripts/gen-error-codes.ts from src/error-catalog.ts — do not edit by hand. -->",
    "",
    "# ArchLang error codes",
    "",
    "Every diagnostic carries a stable code. Look one up with `arch explain <CODE>`",
    "(e.g. `arch explain E_ROOM_SIZE`). Errors abort rendering; warnings do not.",
    "",
    `**${errors.length} errors** · **${warnings.length} warnings**`,
    "",
    "| Code | Severity | Summary |",
    "| --- | --- | --- |",
    ...ERROR_CODES.map(
      (c) => `| [\`${c}\`](#${c.toLowerCase()}) | ${ERROR_CATALOG[c]!.severity} | ${ERROR_CATALOG[c]!.message} |`,
    ),
    "",
  ];

  for (const c of ERROR_CODES) {
    const e = ERROR_CATALOG[c]!;
    out.push(
      `## ${c}`,
      "",
      `*${e.severity}* — ${e.message}`,
      "",
      `**Cause.** ${e.cause}`,
      "",
      `**Fix.** ${e.fix}`,
      "",
      // `arch static`, never a bare `arch` fence. The docs site rewrites every plain
      // ```arch fence into a live-compiling <ArchLive> widget, and a catalog example is
      // a FRAGMENT that demonstrates a fault — so going live turned 104 of these into
      // red cards on https://archlang.uk/errors, most of them reporting a generic
      // `Expected "plan" but found …` that has nothing to do with the code being
      // documented. `static` keeps the ArchLang syntax highlighting and drops the
      // compile. `test/docs-fences.test.ts` holds the line.
      "```arch static",
      e.example,
      "```",
      "",
      // The corrected half of the pair (card AF5), `arch static` for the same reason: most are
      // fragments too, run by test/error-catalog-examples.test.ts wrapped in the smallest plan.
      ...(e.fixed === undefined ? [] : ["**Fixed.**", "", "```arch static", e.fixed, "```", ""]),
    );
  }
  return out.join("\n").replace(/\n+$/, "\n");
}

/** Where {@link renderCatalogFixes} is written. */
export const CATALOG_FIXES_PATH = "src/error-catalog-fixes.ts";
/** Where {@link renderIntentCatalogFixes} is written. */
export const INTENT_CATALOG_FIXES_PATH = "src/error-catalog-fixes-intent.ts";

/**
 * Whether a code is an intent violation's (`E_INTENT_*`): raised only by `validateIntent`, which
 * judges a plan against a brief, never by `compile()`, `lint()` or anything else the playground's
 * compiler chunk runs (card NR.10). Its fix goes in {@link INTENT_CATALOG_FIXES_PATH}, apart from
 * the compile path's column.
 */
export const isIntentCode = (code: string): boolean => code.startsWith("E_INTENT_");

/** One fix-column module: the header, the doc comment and the rows, `name` the exported constant. */
const fixModule = (doc: string, name: string, codes: readonly string[]): string => {
  const rows = codes.map((c) => `  ${c}: ${JSON.stringify(ERROR_CATALOG[c]!.fix)},`);
  return `// GENERATED by scripts/gen-error-codes.ts from src/error-catalog.ts — do not edit by hand. Run \`npm run gen:errors\`.

${doc}
export const ${name}: Readonly<Record<string, string>> = {
${rows.join("\n")}
};
`;
};

/**
 * The full `src/error-catalog-fixes.ts` content: every code's `fix` and nothing else of its entry,
 * in `ERROR_CODES` order, but the intent violations' (`E_INTENT_*`, {@link renderIntentCatalogFixes},
 * card NR.10), each string through `JSON.stringify` (so the module holds the value the catalogue
 * evaluates to, a derived family list included). `diagnosticToJson` reads it, so a bundle that
 * compiles but never explains keeps the remedies without the messages, causes and examples (card
 * RM0.7: the playground's compiler chunk).
 */
export function renderCatalogFixes(): string {
  return fixModule(
    `/**
 * Each catalogue code's \`fix\` but the intent violations', apart from the rest of its entry: what
 * the \`--error-svg\` card \`compile()\` draws reads it (\`catalogFix\`, \`src/catalog-fix.ts\`), and
 * \`diagnosticToJson\` and \`renderErrorSvg\` read it with the intent table (\`anyCatalogFix\`,
 * \`src/any-catalog-fix.ts\`). Kept out of \`ERROR_CATALOG\`'s module so that a bundle which compiles
 * but never explains (the playground's compiler chunk, card RM0.7) carries the remedies without the
 * messages, causes and examples. The intent violations' (\`E_INTENT_*\`, card NR.10), which
 * \`compile()\` never raises, are in \`src/error-catalog-fixes-intent.ts\`, off the compile path.
 * Generated from \`ERROR_CATALOG\`, never typed: \`test/explain.test.ts\` and \`check:drift\` fail when
 * it goes stale.
 */`,
    "CATALOG_FIXES",
    ERROR_CODES.filter((c) => !isIntentCode(c)),
  );
}

/**
 * The full `src/error-catalog-fixes-intent.ts` content: the intent violations' (`E_INTENT_*`) fixes,
 * in `ERROR_CODES` order, written as {@link renderCatalogFixes} writes the rest (card NR.10).
 */
export function renderIntentCatalogFixes(): string {
  return fixModule(
    `/**
 * The intent violations' (\`E_INTENT_*\`) \`fix\` column, apart from every other code's
 * (\`src/error-catalog-fixes.ts\`, card NR.10): only \`validateIntent\` raises these codes, never
 * \`compile()\`, so the compile path's column (the playground's compiler chunk, which the
 * \`--error-svg\` card reads) leaves them out. \`anyCatalogFix\` (\`src/any-catalog-fix.ts\`) reads
 * this one after it, for \`diagnosticToJson\` and \`renderErrorSvg\`; nothing on the compile path does.
 * Generated from \`ERROR_CATALOG\`, never typed: \`test/explain.test.ts\` and \`check:drift\` fail when
 * it goes stale.
 */`,
    "INTENT_CATALOG_FIXES",
    ERROR_CODES.filter(isIntentCode),
  );
}

function main(): void {
  writeFileSync(resolve(ROOT, "docs/error-codes.md"), renderErrorCodes());
  writeFileSync(resolve(ROOT, CATALOG_FIXES_PATH), renderCatalogFixes());
  writeFileSync(resolve(ROOT, INTENT_CATALOG_FIXES_PATH), renderIntentCatalogFixes());
  process.stdout.write(
    `✓ generated docs/error-codes.md, ${CATALOG_FIXES_PATH} and ${INTENT_CATALOG_FIXES_PATH} from src/error-catalog.ts\n`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
