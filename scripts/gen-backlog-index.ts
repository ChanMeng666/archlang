/**
 * Generate `docs/backlog-index.md`: one table row per entry of `docs/backlog.md` (id, title, status,
 * section, a link to the heading), so the `/loop` driver and a reader find the topmost `todo` without
 * reading the 140 KB file (card EH3.2).
 *
 * The backlog is the source of truth: every `### ` heading must read
 * `### <id> · <title> — \`<status>\``. An unknown status or a repeated id fails the generator.
 * The closed statuses are not valid here: `scripts/backlog-archive.mjs` moves those entries to the
 * private lab repository. {@link parseEntries} and {@link renderIndex} are pure so
 * `test/backlog-index.test.ts` can regenerate in memory. Run `npm run gen:backlog-index`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const BACKLOG = "docs/backlog.md";
const INDEX = "docs/backlog-index.md";

/** The statuses a kept heading may carry; everything else is archived. */
export const STATUSES = ["todo", "declared", "parked", "deferred", "decision", "note"] as const;
export type BacklogStatus = (typeof STATUSES)[number];

export interface BacklogEntry {
  id: string;
  title: string;
  status: BacklogStatus;
  section: string;
  /** The heading line without its `### `. */
  heading: string;
  /** GitHub's anchor for the heading, de-duplicated across the file. */
  anchor: string;
}

const HEADING = /^### (\S+) · (.+) — `([^`]+)`$/;

/** GitHub's heading slug: markdown stripped, lower-cased, punctuation dropped, spaces to hyphens. */
export function slug(heading: string): string {
  return heading
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/`/g, "")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\p{M} _-]/gu, "")
    .replace(/ /g, "-");
}

/** Every `### ` entry of the backlog, in file order; throws on an unreadable heading or a repeated id. */
export function parseEntries(src: string): BacklogEntry[] {
  const seenAnchors = new Map<string, number>();
  const anchor = (text: string): string => {
    const base = slug(text);
    const n = seenAnchors.get(base) ?? 0;
    seenAnchors.set(base, n + 1);
    return n === 0 ? base : `${base}-${n}`;
  };
  const entries: BacklogEntry[] = [];
  const ids = new Set<string>();
  let section = "";
  let fenced = false;
  for (const line of src.replace(/\r\n/g, "\n").split("\n")) {
    if (/^```/.test(line)) fenced = !fenced;
    if (fenced) continue;
    if (/^## /.test(line)) {
      section = line
        .slice(3)
        .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
        .replace(/`/g, "");
      anchor(line.slice(3));
      continue;
    }
    if (!/^### /.test(line)) continue;
    const heading = line.slice(4);
    const a = anchor(heading);
    const m = HEADING.exec(line);
    if (!m) throw new Error(`${BACKLOG}: heading is not \`### <id> · <title> — \`<status>\`\`: ${line}`);
    const [, id, title, status] = m as unknown as [string, string, string, string];
    if (!(STATUSES as readonly string[]).includes(status)) {
      throw new Error(`${BACKLOG}: ${id} has status \`${status}\`; allowed: ${STATUSES.join(", ")}`);
    }
    if (ids.has(id)) throw new Error(`${BACKLOG}: duplicate id ${id}`);
    ids.add(id);
    entries.push({ id, title, status: status as BacklogStatus, section, heading, anchor: a });
  }
  return entries;
}

const cell = (s: string): string => s.replace(/[\\|]/g, "\\$&");

/** The whole generated file. */
export function renderIndex(entries: readonly BacklogEntry[]): string {
  const rows = entries.map(
    (e) => `| ${cell(e.id)} | ${cell(e.title)} | \`${e.status}\` | ${cell(e.section)} | [↗](backlog.md#${e.anchor}) |`,
  );
  const count = (s: string): number => entries.filter((e) => e.status === s).length;
  return [
    "# Backlog index",
    "",
    "<!-- GENERATED by `npm run gen:backlog-index` from docs/backlog.md; do not edit -->",
    "",
    `${entries.length} entries (${STATUSES.map((s) => `${count(s)} ${s}`).join(", ")}), in the order of \`docs/backlog.md\`.`,
    "The `/loop` driver takes the topmost `todo` row and opens that one entry through its link.",
    "",
    "| Id | Title | Status | Section | Entry |",
    "|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

function main(): void {
  const entries = parseEntries(readFileSync(resolve(ROOT, BACKLOG), "utf8"));
  writeFileSync(resolve(ROOT, INDEX), renderIndex(entries));
  process.stdout.write(`✓ generated ${entries.length} rows in ${INDEX}\n`);
}

// Run only when invoked directly (not when imported by the test).
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
