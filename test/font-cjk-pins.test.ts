/** the CJK font package's version, its exact pin in the core, its files and its recorded SHA-256 are pinned on every PR (release.yml only checked the version at tag time) */

import { existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
// @ts-expect-error -- a plain .mjs script with no declaration file
import { fontPinProblem } from "../scripts/check-font-pin.mjs";
import { sha256 } from "./helpers/digest.js";

/**
 * `packages/font-cjk` ships a ~11 MB font binary that is COMMITTED (generated by
 * `npm run gen:font-cjk`, outside the drift gate), so every figure here is checked offline against
 * the file on disk. What stays release-time, in `release.yml`: whether that version is already on
 * npm, and the publish itself. Nothing here touches the network.
 *
 * The one pin of the font's version outside its own manifest is the core's exact
 * `optionalDependencies` entry (`package-lock.json` is derived and excluded). The comparison is
 * `scripts/check-font-pin.mjs`, the same code `release.yml` runs, never retyped. The font-to-
 * `.sha256` match is also asserted in `test/export-font-cjk.test.ts`; here it pins the file's
 * format as well.
 */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PKG_DIR = resolve(ROOT, "packages/font-cjk");
const manifest = JSON.parse(readFileSync(resolve(PKG_DIR, "package.json"), "utf8")) as {
  name: string;
  version: string;
  main: string;
  types: string;
  files: string[];
  exports: Record<string, { types: string; import: string }>;
};

describe("packages/font-cjk pins", () => {
  it("the core pins the font at exactly the package's version", () => {
    expect(fontPinProblem(ROOT)).toBeNull();
    const core = JSON.parse(readFileSync(resolve(ROOT, "package.json"), "utf8")) as {
      optionalDependencies: Record<string, string>;
    };
    expect(core.optionalDependencies[manifest.name]).toBe(manifest.version);
    expect(manifest.version).toMatch(/^\d+\.\d+\.\d+$/);
  });

  it("every declared file, main, types and export target exists", () => {
    const targets = [
      ...manifest.files,
      manifest.main,
      manifest.types,
      ...Object.values(manifest.exports).flatMap((e) => [e.types, e.import]),
    ].map((p) => p.replace(/^\.\//, ""));
    for (const t of targets) expect(existsSync(resolve(PKG_DIR, t)), t).toBe(true);
    expect(manifest.files).toContain("ArchLangCJKSans-Regular.otf");
    expect(manifest.files).toContain("ArchLangCJKSans-Regular.otf.sha256");
  });

  it("the recorded SHA-256 is well formed and is the committed font's", () => {
    const line = readFileSync(resolve(PKG_DIR, "ArchLangCJKSans-Regular.otf.sha256"), "utf8");
    expect(line).toMatch(/^[0-9a-f]{64} {2}ArchLangCJKSans-Regular\.otf\r?\n?$/);
    expect(line.split(/\s+/)[0]).toBe(sha256(readFileSync(resolve(PKG_DIR, "ArchLangCJKSans-Regular.otf"))));
  });
});
