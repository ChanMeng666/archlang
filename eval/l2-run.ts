/**
 * L2 harness runner — the decisive loop-vs-equal-budget-resampling experiment
 * (roadmap Tranche 3, T3). This is the ONE file that talks to the network: it wraps the
 * resolved provider's endpoint (OpenAI chat completions or the Anthropic Messages API,
 * picked by run.ts's `resolveProvider`) as an {@link L2Author} and drives the pure
 * protocol in `l2.ts` across the corpus for `--trials` repetitions, producing
 * `eval/results.l2.<model>.{md,json}` (one pair per model, so a second model never
 * overwrites the first).
 *
 * T3 status: ONE owner-ratified live run (2026-11-15), within the bounds in
 * `docs/agents/iron-laws.md` (provider anthropic; claude-sonnet-5-5 and claude-haiku-5-5;
 * analysis and decision rule pre-registered in a dated file before the run; the result
 * published whatever it shows). Until that result is published, no loop-gain claim and no
 * claim of its absence; after that, claims cite only that run's published record. Any
 * other live run needs a new owner decision.
 *
 * Like `eval:live`, it is **guarded**: without `--yes` (or `ARCHLANG_EVAL_CONFIRM=1`)
 * it prints the plan (provider, model, briefs, trials, a rough call estimate, budget,
 * output paths) and exits `3` WITHOUT calling any API. `--budget <n>tok|<n>usd` is a
 * cumulative circuit breaker (reusing run.ts's `LiveLedger`), checked once at the start
 * of each brief; `--max <n>` caps briefs; `--trials <n>` (default 3) sets repetitions;
 * `--concurrency <n>` (default 4) runs briefs in parallel — each brief's loop→control
 * arms stay serial because the control's budget is the loop's *measured* token spend
 * (Olausson equal budget).
 *
 * Reproducibility: OpenAI reasoning endpoints reject a non-default temperature, so the
 * only lever is `seed`. Seeds are fully derived from constants below so a re-run is
 * reproducible-by-record; `max_completion_tokens` is 16384 (reasoning models spend
 * thinking tokens from the completion cap — a smaller cap measures the budget, not the
 * model). The Anthropic API has no `seed`, so there the seeds are record labels only, and
 * NO `temperature` is sent: the 5.5 models reject it (PR #295), and a pinned temperature
 * would make the control arm's "i.i.d." resamples near-copies of one another. This is
 * deliberately not run.ts's retry-with-temperature-0 path.
 *
 * Run: `npm run eval:l2 -- --yes [--max N] [--trials N] [--budget <n>tok|usd] [--concurrency N]`.
 */

